-- SCRAP 계정: api_rst (범용 결과 저장소, api_id 로 리스트 파티션)
--
-- 두 층 중 아래층이다. 타입 테이블을 따로 만들지 않는 소스가 전부 여기
-- 들어오고, 조회는 뷰로 한다 (04_scrap_views.sql).
--
-- 왜 아래층을 두는가: 운용사가 하나 늘 때마다 models.py 에 클래스를 더하고
-- **배포까지** 해야 했다. 뷰는 DB 안에서 끝난다. 소스가 필드를 추가해도
-- JSON 에는 그냥 들어온다 -- 타입 테이블에서는 조용히 버려졌다.
--
-- 대가는 측정해 두었다 (20만 행 합성 데이터, 26ai):
--   저장        58 -> 225 B/행  (3.9x)
--   전체 추출   1.0x   -- 전송이 지배해서 차이가 묻힌다
--   하루치      1.1x   -- 단, 그 JSON 경로에 함수기반 인덱스가 있을 때
--   전수 집계   2.5x   -- 여기서만 비용이 든다
-- 분석 쪽이 Parquet 을 읽는 구조라 JSON 전개는 하루 한 번만 치른다.
--
-- 그래서 행 수의 대부분을 차지하는 표(상위 7개가 80%)는 위층에 남겼다.

-- ---------------------------------------------------------------------------
-- 파티션
-- ---------------------------------------------------------------------------
-- LIST (api_id) AUTOMATIC: 새 api_id 가 들어오면 파티션이 저절로 생긴다.
-- 확인함 -- 세 소스를 넣으니 SYS_P 파티션이 세 개 생겼고, 뷰의
-- "WHERE api_id = ..." 가 프루닝으로 한 파티션만 읽었다 (plan: part 2..2).
--
-- 이것이 없으면 43개 소스가 한 표에 섞여 506K 행이 20M 행이 되고, 한 소스를
-- 읽을 때마다 다른 소스 행을 골라내는 비용이 따라붙는다. 프루닝은 그 비용을
-- 0 으로 만든다 -- 다른 파티션은 열지 않는다.
--
-- p_seed 는 자리를 만들기 위한 것이다. AUTOMATIC 도 최초 파티션 하나는
-- 요구한다. 들어올 일이 없는 값을 둬서 비어 있게 유지한다.
CREATE TABLE api_rst (
  id                 NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
  api_id             VARCHAR2(150 CHAR)  NOT NULL,
  job_id             VARCHAR2(150 CHAR)  NOT NULL,

  -- 레코드 한 건. **row_stamp_json 이 지목한 값까지 합쳐서** 넣는다 --
  -- 타입 테이블에 저장될 행과 같은 모양이다.
  --
  -- v1 은 이것을 둘로 나눠 담았다(key_params_json + result_json). 그래서
  -- 같은 소스의 한 행이 두 컬럼에 걸쳐 있었고, 뷰를 씌우면 컬럼마다 어느
  -- 쪽에서 꺼낼지를 알아야 했다 -- 실제로 ace_etf_pdf 의 fundcd/std_dt 는
  -- result_json 에 없다. 합쳐 두면 뷰가 '$.<컬럼명>' 하나로 끝나고,
  -- 타입 테이블로 승격할 때도 모양이 이미 같다.
  --
  -- 나눠 담아 아끼던 공간은 행당 키 두세 개뿐이고, 잃던 것은 뷰의 단순함과
  -- 두 층 사이의 호환이었다.
  --
  -- 키는 **소문자로 접어서** 넣는다 -- 뷰의 JSON 경로가 예측 가능해야 하고,
  -- 지금은 원본 키가 그대로 들어가서 소스마다 표기가 다르다 (ACE 는
  -- std_DT, KRX 는 전부 대문자). 타입 테이블은 VendorRecordBase 가 이미
  -- 같은 접기를 한다.
  result_json        JSON                NOT NULL,

  -- 어느 날짜분인가. api_job_log.target_day 와 같은 뜻이고, 보존 정리와
  -- 재적재(그날 것만 지우고 다시 넣기)가 이 컬럼을 쓴다.
  target_day         VARCHAR2(8 CHAR),

  updated_at         DATE DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT pk_api_rst PRIMARY KEY (id)
)
PARTITION BY LIST (api_id) AUTOMATIC
  (PARTITION p_seed VALUES ('__SEED__'));

-- ---------------------------------------------------------------------------
-- 인덱스
-- ---------------------------------------------------------------------------
-- job_id 는 GLOBAL 이다. save_mode='overwrite' 의 선행 삭제가 job_id 로만
-- 지우는데, LOCAL 이면 모든 파티션의 인덱스를 훑어야 한다. job_id 에 api_id
-- 가 들어 있는 것이 관례지만 보장은 아니라서 프루닝에 기댈 수 없다.
CREATE INDEX ix_api_rst_job ON api_rst (job_id) GLOBAL;

-- 날짜 정리/재적재용. api_id 와 함께 쓰이므로 LOCAL 이면 프루닝과 겹쳐
-- 동작한다.
CREATE INDEX ix_api_rst_day ON api_rst (target_day) LOCAL;

-- JSON 경로 인덱스는 소스마다 다르므로 여기 두지 않는다. 조회에 실제로
-- 쓰는 경로가 생길 때 04_scrap_views.sql 말미의 형태로 더한다 -- 미리
-- 전부 걸면 적재가 느려지고 대부분은 쓰이지 않는다.

COMMENT ON TABLE  api_rst IS '타입 테이블이 없는 소스의 결과. 조회는 v_* 뷰로';
COMMENT ON COLUMN api_rst.result_json IS '레코드 한 건 + 스탬프된 키. 키는 소문자로 접어 넣는다';
COMMENT ON COLUMN api_rst.target_day  IS 'YYYYMMDD. 재적재와 보존 정리가 쓴다';
